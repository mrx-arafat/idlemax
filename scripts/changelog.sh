#!/usr/bin/env bash
# Builds CHANGELOG.md (Keep a Changelog) from Conventional Commit subjects, one section
# per v* tag. Never edit CHANGELOG.md by hand: fix the history or this script and re-run.
#
# Usage: scripts/changelog.sh [--tag vX.Y.Z] [output]
#   --tag vX.Y.Z  label the commits after the newest tag as that release, dated today, so
#                 the changelog can be committed before the tag is created.
#   output        defaults to CHANGELOG.md at the repository root.
#
# feat -> Added, refactor and perf -> Changed, fix -> Fixed, docs -> Documentation; other
# types and non-conventional subjects are skipped. Same history and arguments give
# byte-identical output, and the file is rewritten only when its content changes.
# Portable to macOS bash 3.2 and BSD awk/sed; needs only git.
set -euo pipefail

die() {
  printf 'changelog: %s\n' "$*" >&2
  exit 1
}

usage() {
  sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
}

next_tag=""
out=""
while [ $# -gt 0 ]; do
  case "$1" in
    --tag)
      [ $# -ge 2 ] || die "--tag needs a version such as v0.1.0"
      next_tag=$2
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    -*) die "unknown option: $1" ;;
    *)
      [ -z "$out" ] || die "only one output path is allowed"
      out=$1
      shift
      ;;
  esac
done

root=$(git rev-parse --show-toplevel 2>/dev/null) || die "not inside a git repository"
out=${out:-$root/CHANGELOG.md}

case "$next_tag" in
  "" | v[0-9]*) ;;
  *) die "--tag must look like v0.1.0, got: $next_tag" ;;
esac
if [ -n "$next_tag" ] && git -C "$root" rev-parse -q --verify "refs/tags/$next_tag" >/dev/null; then
  die "tag $next_tag already exists; run without --tag"
fi

has_head=0
if git -C "$root" rev-parse -q --verify HEAD >/dev/null; then
  has_head=1
fi

# Release tags reachable from HEAD, newest first, with the pending --tag in front.
versions=()
[ -z "$next_tag" ] || versions+=("$next_tag")
if [ "$has_head" -eq 1 ]; then
  while IFS= read -r t; do
    versions+=("$t")
  done < <(git -C "$root" tag --list 'v[0-9]*' --merged HEAD --sort=-version:refname)
fi
count=${#versions[@]}

# Prints the Keep a Changelog subsections for one git revision range.
render() {
  local range=$1 note=$2
  if [ "$has_head" -eq 0 ] || [ -z "$range" ]; then
    [ -z "$note" ] || printf '\n%s\n' "$note"
    return 0
  fi
  git -C "$root" log --no-merges --reverse --format='%s' "$range" | awk -v note="$note" '
    function cap(s) { return toupper(substr(s, 1, 1)) substr(s, 2) }
    {
      if (!match($0, /^[A-Za-z]+(\([^)]*\))?!?: +/)) next
      head = substr($0, 1, RLENGTH)
      desc = substr($0, RLENGTH + 1)
      sub(/[ \t]+$/, "", desc)
      if (desc == "") next
      sub(/: +$/, "", head)
      type = tolower(head)
      sub(/[(!].*$/, "", type)
      if (type == "feat") g = 1
      else if (type == "refactor" || type == "perf") g = 2
      else if (type == "fix") g = 3
      else if (type == "docs") g = 4
      else next
      line = "- "
      if (head ~ /!$/) line = line "**Breaking:** "
      if (match(head, /\([^)]*\)/)) line = line "**" substr(head, RSTART + 1, RLENGTH - 2) ":** "
      items[g] = items[g] line cap(desc) "\n"
      any = 1
    }
    END {
      split("Added Changed Fixed Documentation", names, " ")
      for (g = 1; g <= 4; g++) {
        if (items[g] != "") printf "\n### %s\n\n%s", names[g], items[g]
      }
      if (!any && note != "") printf "\n%s\n", note
    }'
}

# https URL of a GitHub origin, for compare links; empty for anything else.
web_url() {
  local origin
  origin=$(git -C "$root" remote get-url origin 2>/dev/null) || return 0
  printf '%s\n' "$origin" |
    sed -E -n 's#^(git@|ssh://git@|https://)github\.com[:/]([^/]+/[^/]+)$#https://github.com/\2#p' |
    sed -E 's#\.git$##'
}

tmp=$(mktemp "${out}.XXXXXX")
trap 'rm -f "$tmp"' EXIT

{
  printf '# Changelog\n\n'
  printf '<!-- Generated by scripts/changelog.sh from Conventional Commit subjects. Do not edit by hand; re-run the script instead. -->\n\n'
  printf 'All notable changes to this project are documented in this file.\n'
  printf 'The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.1.0/), and this project adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html).\n'

  printf '\n## [Unreleased]\n'
  if [ -n "$next_tag" ]; then
    render "" ""
  elif [ "$count" -gt 0 ]; then
    render "${versions[0]}..HEAD" ""
  else
    render "HEAD" ""
  fi

  for ((i = 0; i < count; i++)); do
    v=${versions[i]}
    if [ "$i" -eq 0 ] && [ -n "$next_tag" ]; then
      end=HEAD
      day=$(date +%Y-%m-%d)
    else
      end=$v
      # Tagger date for annotated tags, commit date for lightweight ones.
      day=$(git -C "$root" for-each-ref --format='%(creatordate:short)' "refs/tags/$v")
    fi
    if [ $((i + 1)) -lt "$count" ]; then
      range="${versions[i + 1]}..$end"
    else
      range=$end
    fi
    printf '\n## [%s] - %s\n' "${v#v}" "$day"
    render "$range" "No notable changes."
  done

  web=$(web_url)
  if [ -n "$web" ] && [ "$count" -gt 0 ]; then
    printf '\n'
    if [ -n "$next_tag" ]; then
      printf '[Unreleased]: %s/compare/%s...HEAD\n' "$web" "$next_tag"
    else
      printf '[Unreleased]: %s/compare/%s...HEAD\n' "$web" "${versions[0]}"
    fi
    for ((i = 0; i < count; i++)); do
      v=${versions[i]}
      if [ $((i + 1)) -lt "$count" ]; then
        printf '[%s]: %s/compare/%s...%s\n' "${v#v}" "$web" "${versions[i + 1]}" "$v"
      else
        printf '[%s]: %s/releases/tag/%s\n' "${v#v}" "$web" "$v"
      fi
    done
  fi
} >"$tmp"

if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
  printf 'changelog: %s is up to date\n' "${out#"$root"/}" >&2
else
  chmod 0644 "$tmp"
  mv -f "$tmp" "$out"
  printf 'changelog: wrote %s\n' "${out#"$root"/}" >&2
fi
